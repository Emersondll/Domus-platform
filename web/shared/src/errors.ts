/** Texto em português para o `detail` do servidor, ou o próprio `detail` quando não houver tradução. */
export function friendlyDetail(detail: string): string {
  if (TEXT[detail]) return TEXT[detail];
  if (detail.startsWith("Too many rows; narrow the period")) return "São linhas demais; reduza o período.";
  if (/ not found$/.test(detail)) return "Não encontrado. Pode ter sido removido; atualize a tela.";
  return detail;
}

/** Há tradução específica para esta mensagem? */
export function hasFriendlyDetail(detail: string): boolean {
  return friendlyDetail(detail) !== detail;
}
